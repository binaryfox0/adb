int my_spake2_process_msg(
        my_spake2_t *ctx, 
        uint8_t *out_key, 
        size_t *out_key_len,
        const size_t max_out_key_len, 
        const uint8_t *their_msg,
        const size_t their_msg_len)
{
    return spake2_process_msg(
            ctx,
            out_key, out_key_len, max_out_key_len,
            their_msg, their_msg_len);
}

void my_spake2_free(
        my_spake2_t *ctx)
{
    spake2_ctx_free(ctx);
}

