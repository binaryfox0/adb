#include "my_spake2.h"

#include "spake2.h"

#include <string.h>

my_spake2_t *my_spake2_new(
        const int is_alice,
        const uint8_t *my_name,
        const size_t my_name_len,
        const uint8_t *their_name,
        const size_t their_name_len)
{
    return spake2_ctx_create(
            NULL,
            is_alice ? SPAKE2_ROLE_ALICE : SPAKE2_ROLE_BOB,
            my_name,
            my_name_len,
            their_name,
            their_name_len);

}

