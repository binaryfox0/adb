int spake2_generate_msg(
        spake2_ctx_t *ctx, 
        uint8_t *out, 
        size_t *out_len,
        const size_t max_out_len, 
        const uint8_t *password,
        const size_t password_len,
        const uint8_t random_data[SPAKE2_RANDOM_DATA_LENGTH])
{
    spake2__sc_wide_t private_tmp = {0};
    spake2__sc_t private_reduced = {0};

    spake2__sc_wide_t password_tmp = {0};
    spake2__sc_t password_reduced = {0};

    spake2__u256_t password_scalar = {0};
    spake2__ge_p3_t P = {0};
    spake2__ge_p3_t mask = {0};
    spake2__ge_cached_t mask_cached = {0};
    spake2__ge_p1p1_t Pstar = {0};
    spake2__ge_p2_t Pstar_proj = {0};
    if(
            !ctx || 
            ctx->state != SPAKE2_STATE_INIT ||
            !out || !out_len || 
            max_out_len < sizeof(ctx->my_msg) || 
            (!password ^ (password_len == 0)) ||
            !random_data)
        return 0;
    
    memcpy(&private_tmp, random_data, SPAKE2_RANDOM_DATA_LENGTH);
    spake2__sc_reduce(&private_reduced, &private_tmp);
    spake2__sc_lshift3(&private_reduced);
    ctx->private_key = private_reduced;

    spake2__ge_scalarmult_base(&P, &ctx->private_key);
    mbedtls_sha512(password, 
            password_len, password_tmp.v, 0);
    memcpy(ctx->password_hash, &password_tmp, SPAKE2__SHA512_DIGEST_LENGTH);
    spake2__sc_reduce(&password_reduced, &password_tmp);
    memcpy(&password_scalar, &password_reduced, sizeof(password_scalar));

    if(!ctx->disable_password_scalar_hack)
    {
        spake2__u256_t order =
        {{
            0x5812631a5cf5d3edULL,
            0x14def9dea2f79cd6ULL,
            0x0000000000000000ULL,
            0x1000000000000000ULL
        }};
        spake2__u256_t tmp = {0};

        spake2__u256_cmov(&tmp, &order, &tmp,
                    spake2__ctime_eq_w(password_scalar.v[0] & 1, 1));
        spake2__u256_add(&password_scalar, &password_scalar, &tmp);

        spake2__u256_add(&order, &order, &order);
        memset(&tmp, 0, sizeof(tmp));
        spake2__u256_cmov(&tmp, &order, &tmp,
                    spake2__ctime_eq_w(password_scalar.v[0] & 2, 2));
        spake2__u256_add(&password_scalar, &password_scalar, &tmp);

        spake2__u256_add(&order, &order, &order);
        memset(&tmp, 0, sizeof(tmp));
        spake2__u256_cmov(&tmp, &order, &tmp,
                    spake2__ctime_eq_w(password_scalar.v[0] & 4, 4));
        spake2__u256_add(&password_scalar, &password_scalar, &tmp);
    }

    ctx->password_scalar = password_scalar;
    spake2__ge_scalarmult_small_precomp(
            &mask, (uint8_t*)&ctx->password_scalar, 
            ctx->my_role == SPAKE2_ROLE_ALICE ?
                spake2__m_small_precomp :
                spake2__n_small_precomp);
    spake2__ge_p3_to_cached(&mask_cached, &mask);
    spake2__ge_add(&Pstar, &P, &mask_cached);
    spake2__ge_p1p1_to_p2(&Pstar_proj, &Pstar);
    spake2__ge_to_bytes(ctx->my_msg, &Pstar_proj);
  
    memcpy(out, ctx->my_msg, sizeof(ctx->my_msg));
    *out_len = sizeof(ctx->my_msg);
    ctx->state = SPAKE2_STATE_MSG_GENERATED;
    return 1;
}

#define SPAKE2__MIN(a, b) ((a) < (b) ? (a) : (b))

static void spake2__update(
        mbedtls_sha512_context *sha, 
        const uint8_t *data,
        const size_t len) 
{
    uint8_t len_le[8] = {0};
    size_t l = len;

    for(int i = 0; i < 8; i++) 
    {
      len_le[i] = l & 0xff;
      l >>= 8;
    }

    mbedtls_sha512_update(sha, len_le, sizeof(len_le));
    mbedtls_sha512_update(sha, data, len);
}

int spake2_process_msg(
        spake2_ctx_t *ctx, 
        uint8_t *out_key, 
        size_t *out_key_len,
        size_t max_out_key_len, 
        const uint8_t *their_msg,
        size_t their_msg_len) 
{
    spake2__ge_p3_t Qstar = {0};
    spake2__ge_p3_t peers_mask = {0};
    spake2__ge_cached_t peers_mask_cached = {0};
    spake2__ge_p1p1_t Q_compl = {0};
    spake2__ge_p3_t Q_ext = {0};
    spake2__ge_p2_t dh_shared = {0};
    uint8_t dh_shared_encoded[32] = {0};
    mbedtls_sha512_context sha = {0};
    uint8_t key[SPAKE2__SHA512_DIGEST_LENGTH] = {0};
    if(
            !ctx || 
            ctx->state != SPAKE2_STATE_MSG_GENERATED ||
            !out_key || !out_key_len || 
            (!their_msg ^ (their_msg_len == 0)) || 
            their_msg_len != 32)
        return 0;

    if (!spake2__ge_from_bytes_vartime(&Qstar, their_msg)) 
    {
        // Point received from peer was not on the curve.
        return 0;
    }

    // Unmask peer's value.
    spake2__ge_scalarmult_small_precomp(
            &peers_mask, 
            (uint8_t*)&ctx->password_scalar,
            ctx->my_role == SPAKE2_ROLE_ALICE ? 
                spake2__n_small_precomp : 
                spake2__m_small_precomp);

    spake2__ge_p3_to_cached(&peers_mask_cached, &peers_mask);

    spake2__ge_sub(&Q_compl, &Qstar, &peers_mask_cached);
    spake2__ge_p1p1_to_p3(&Q_ext, &Q_compl);

    spake2__ge_scalarmult(&dh_shared, &ctx->private_key, &Q_ext);

    spake2__ge_to_bytes(dh_shared_encoded, &dh_shared);

    mbedtls_sha512_init(&sha);
    mbedtls_sha512_starts(&sha, 0);
    if (ctx->my_role == SPAKE2_ROLE_ALICE) 
    {
        spake2__update(&sha, ctx->my_name, ctx->my_name_len);
        spake2__update(&sha, ctx->their_name, ctx->their_name_len);
        spake2__update(&sha, ctx->my_msg, sizeof(ctx->my_msg));
        spake2__update(&sha, their_msg, 32);
    } else {
        spake2__update(&sha, ctx->their_name, ctx->their_name_len);
        spake2__update(&sha, ctx->my_name, ctx->my_name_len);
        spake2__update(&sha, their_msg, 32);
        spake2__update(&sha, ctx->my_msg, sizeof(ctx->my_msg));
    }
    spake2__update(&sha, dh_shared_encoded, 
            sizeof(dh_shared_encoded));
    spake2__update(&sha, ctx->password_hash,
            sizeof(ctx->password_hash));

    // problem right here, not produce the same key
    mbedtls_sha512_finish(&sha, key);

    size_t to_copy =  SPAKE2__MIN(max_out_key_len, sizeof(key));
    memcpy(out_key, key, to_copy);
    *out_key_len = to_copy;
    ctx->state = SPAKE2_STATE_KEY_GENERATED;

    return 1;
}

void spake2_ctx_free(
        spake2_ctx_t *ctx)
{
    spake2_allocator_t allocator = {0};
    if(!ctx)
        return;
    
    allocator = ctx->allocator;
    allocator.free(allocator.userdata, ctx->my_name);
    allocator.free(allocator.userdata, ctx->their_name);
    spake2__cleanese(ctx, sizeof(*ctx));
    allocator.free(allocator.userdata, ctx);
}
